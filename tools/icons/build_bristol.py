"""Generates the Bristol stool type illustrations (SPEC 3.3) as Android vector drawables.

Drawn for this app (not traced from the copyrighted original chart): simple single-colour
shapes on a 48x32 canvas, tinted at runtime so they work in light and dark mode.
Run from the repository root; writes app/src/main/res/drawable/bristol_<n>.xml.
Pass --preview <file.svg> to also write all seven side by side for a quick look.
"""
import math
import random
import sys
from pathlib import Path

W, H = 48, 32


def circle(cx, cy, r):
    return ellipse(cx, cy, r, r)


def ellipse(cx, cy, rx, ry):
    return (f"M{cx - rx:.1f},{cy:.1f} a{rx:.1f},{ry:.1f} 0 1,0 {2 * rx:.1f},0 "
            f"a{rx:.1f},{ry:.1f} 0 1,0 {-2 * rx:.1f},0 Z")


def blob(cx, cy, rx, ry, points, jitter, seed, smooth=False):
    """A closed outline around (cx, cy); jitter roughens the edge, smooth draws curves instead of corners."""
    rnd = random.Random(seed)
    pts = []
    for i in range(points):
        a = 2 * math.pi * i / points
        k = 1 + rnd.uniform(-jitter, jitter)
        pts.append((cx + rx * k * math.cos(a), cy + ry * k * math.sin(a)))
    if not smooth:
        return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z"
    # Quadratic curves through midpoints give a soft, wobbly outline.
    mids = [((pts[i][0] + pts[(i + 1) % points][0]) / 2, (pts[i][1] + pts[(i + 1) % points][1]) / 2) for i in range(points)]
    d = f"M{mids[-1][0]:.1f},{mids[-1][1]:.1f}"
    for i in range(points):
        d += f" Q{pts[i][0]:.1f},{pts[i][1]:.1f} {mids[i][0]:.1f},{mids[i][1]:.1f}"
    return d + " Z"


# Each type: list of (path data, fill type). evenOdd cuts the crack notches out of type 3.
TYPES = {
    # 1: separate hard lumps, like nuts
    1: [(" ".join(circle(x, y, r) for x, y, r in
                  [(8, 19, 4), (16.5, 11.5, 4.3), (18, 22, 3.8), (26.5, 16, 4.4), (35.5, 11.5, 3.8), (38, 21.5, 4.2)]), "nonZero")],
    # 2: sausage-shaped but lumpy (fused lumps)
    2: [(" ".join(circle(x, y, r) for x, y, r in
                  [(8, 17, 5.2), (15, 15, 5.8), (22.5, 17, 5.6), (30, 15.5, 5.8), (37.5, 16.5, 5.4)]), "nonZero")],
    # 3: sausage with cracks on its surface (narrow slits cut in from the top edge)
    3: [("M10,9.5 H38 A6.5,6.5 0 0,1 38,22.5 H10 A6.5,6.5 0 0,1 10,9.5 Z "
         "M14.6,9.6 L16.8,9.6 L16.8,13 L15.9,15.8 Z M23,9.6 L25.2,9.6 L24.4,12.6 L24.9,16.5 Z "
         "M30.8,9.6 L32.9,9.6 L32.1,13.4 Z", "evenOdd")],
    # 4: smooth, soft sausage or snake
    4: [("stroke:M7,17.5 C14,12 22,12.5 28,16 S38,19.5 41.5,15", "stroke")],
    # 5: soft blobs with clear-cut edges
    5: [(" ".join([ellipse(10, 18.5, 6, 4.4), ellipse(23.5, 13.5, 6.6, 4.8), ellipse(37, 19, 6.2, 4.4)]), "nonZero")],
    # 6: fluffy pieces with ragged edges, mushy
    6: [(" ".join([blob(15, 16.5, 11, 7, 18, 0.3, 3, smooth=True), blob(34.5, 18, 9, 6, 15, 0.32, 11, smooth=True),
                   blob(44, 12, 2.2, 1.8, 7, 0.25, 5, smooth=True)]), "nonZero")],
    # 7: watery, no solid pieces: a flat, uneven puddle with a few splashes beside it
    7: [(" ".join([blob(22, 21, 17, 4.2, 14, 0.18, 7, smooth=True), blob(33, 18.5, 8, 3.2, 10, 0.2, 9, smooth=True),
                   ellipse(43.5, 23, 1.6, 1.1), ellipse(4.5, 18.5, 1.3, 0.9), ellipse(44.5, 17, 1.1, 0.8)]), "nonZero")],
}


def vector_xml(parts):
    body = []
    for d, kind in parts:
        if kind == "stroke":
            body.append(f'    <path android:pathData="{d[len("stroke:"):]}" android:strokeColor="#FF000000" '
                        f'android:strokeWidth="8" android:strokeLineCap="round" android:fillColor="#00000000" />')
        else:
            body.append(f'    <path android:pathData="{d}" android:fillColor="#FF000000" android:fillType="{kind}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/icons/build_bristol.py; edit that script, not this file. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{W}dp" android:height="{H}dp" android:viewportWidth="{W}" android:viewportHeight="{H}">\n'
            + "\n".join(body) + "\n</vector>\n")


def preview_svg(path):
    cells = []
    for n, parts in TYPES.items():
        x = (n - 1) * (W + 8)
        shapes = []
        for d, kind in parts:
            if kind == "stroke":
                shapes.append(f'<path d="{d[len("stroke:"):]}" fill="none" stroke="#7A5232" stroke-width="8" stroke-linecap="round"/>')
            else:
                rule = "evenodd" if kind == "evenOdd" else "nonzero"
                shapes.append(f'<path d="{d}" fill="#7A5232" fill-rule="{rule}"/>')
        cells.append(f'<g transform="translate({x},0)"><rect width="{W}" height="{H}" fill="#F4F0EA"/>{"".join(shapes)}</g>')
    Path(path).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{7 * (W + 8)}" height="{H}">{"".join(cells)}</svg>')


if __name__ == "__main__":
    out = Path("app/src/main/res/drawable")
    for n, parts in TYPES.items():
        (out / f"bristol_{n}.xml").write_text(vector_xml(parts))
    if "--preview" in sys.argv:
        preview_svg(sys.argv[sys.argv.index("--preview") + 1])
